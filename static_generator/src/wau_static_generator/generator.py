class ReviewRequired(RuntimeError):
    pass


class HardAuditFailure(RuntimeError):
    pass


def _load_decisions(path: str | Path | None) -> dict[str, str]:
    if not path:
        return {}
    p = Path(path)
    if not p.is_file():
        raise FileNotFoundError(p)
    out: dict[str, str] = {}
    with p.open("r", encoding="utf-8-sig", newline="") as f:
        r = csv.DictReader(f, delimiter="\t")
        if not r.fieldnames or "pair" not in r.fieldnames or "action" not in r.fieldnames:
            raise ValueError("Decision TSV must contain pair and action columns")
        for row in r:
            pair = (row.get("pair") or "").strip()
            action = (row.get("action") or "").strip().lower()
            if not pair:
                continue
            if action not in {"preserve", "recompute"}:
                raise ValueError(f"Invalid action for {pair}: {action}")
            out[pair] = action
    return out


def _fmt_scores(scores: dict[str, float]) -> str:
    return "{" + ",".join(f"{c}={float(scores[c]):.6f}" for c in CATEGORIES if scores.get(c, 0.0) > 0) + "}"


def _write_static_lua(path: Path, pair_scores: dict[str, dict[str, float]], game_version: str, build_id: str) -> None:
    lines = [
        f"-- Generated by wau-static-generator {__version__}",
        f"-- Source game version: {game_version}; Steam build: {build_id}",
        "local WAU_STATIC = {",
    ]
    for pair in sorted(pair_scores):
        lines.append(f'["{pair}"]={_fmt_scores(pair_scores[pair])},')
    lines.append("}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _dedupe_unknown(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    seen: set[tuple[str, str]] = set()
    out: list[dict[str, str]] = []
    for row in rows:
        key = (row["pair"], row["effect"])
        if key not in seen:
            seen.add(key)
            out.append(row)
    return sorted(out, key=lambda x: (x["effect"], x["pair"]))


def generate(
    db_root: str | Path,
    baseline_path: str | Path,
    rules_path: str | Path,
    ignored_effects_path: str | Path | None,
    out_dir: str | Path,
    decisions_path: str | Path | None = None,
    allow_unclassified: bool = False,
) -> dict[str, Any]:
    out = Path(out_dir).resolve()
    reports = out / "reports"
    out.mkdir(parents=True, exist_ok=True)
    reports.mkdir(parents=True, exist_ok=True)

    snapshot = Snapshot.load(db_root)
    baseline = Baseline.load(baseline_path)
    rules = Rules(rules_path, ignored_effects_path)

    structural = audit_snapshot(snapshot)
    write_json(reports / "db_audit.json", structural)
    _write_db_audit_md(reports / "DB_AUDIT_REPORT.md", structural)
    write_tsv(reports / "schema_issues.tsv", structural["schema_issues"], ["table", "issue", "detail"])
    write_tsv(reports / "duplicate_keys.tsv", structural["duplicate_keys"], ["table", "key", "source_file"])
    write_tsv(
        reports / "dangling_references.tsv",
        structural["dangling_references"],
        ["table", "row", "field", "value", "expected_target"],
    )
    if structural["status"] != "PASS":
        raise HardAuditFailure("DB structural audit failed; see reports/DB_AUDIT_REPORT.md")

    comparison = compare_baseline(snapshot, baseline)
    write_pair_list(reports / "retained_pairs.tsv", comparison.retained)
    write_pair_list(reports / "added_pairs.tsv", comparison.added)
    write_pair_list(reports / "removed_pairs.tsv", comparison.removed)

    decisions = _load_decisions(decisions_path)
    modified_rows = []
    unresolved_modified: list[str] = []
    recompute_modified: list[str] = []
    preserve_modified: list[str] = []
    for pair in comparison.modified_retained:
        action = decisions.get(pair, "")
        modified_rows.append({
            "pair": pair,
            "action": action,
            "baseline_signature": baseline.signature(pair),
            "current_signature": DataModel(snapshot).pair_source_signature(pair),
        })
        if action == "recompute":
            recompute_modified.append(pair)
        elif action == "preserve":
            preserve_modified.append(pair)
        else:
            unresolved_modified.append(pair)
    write_tsv(
        reports / "modified_retained_pairs.tsv",
        modified_rows,
        ["pair", "action", "baseline_signature", "current_signature"],
    )

    if unresolved_modified:
        _write_update_report(
            reports / "STATIC_UPDATE_REPORT.md",
            baseline,
            snapshot,
            comparison,
            status="REVIEW_REQUIRED",
            confidence=None,
            unknown_count=0,
            notes=f"{len(unresolved_modified)} modified retained pairs require decisions.",
        )
        raise ReviewRequired("Modified retained pairs require preserve/recompute decisions")

    model = DataModel(snapshot)
    # Stable training set: only retained rows whose source inputs did not change.
    train_scores = {p: baseline.scores(p) for p in comparison.unchanged_retained}
    score_pairs = sorted(comparison.added + recompute_modified)
    scored: dict[str, dict[str, float]] = {}
    audits = []
    unknown_rows: list[dict[str, str]] = []
    if score_pairs:
        scorer = LegacyCalibratedScorer(model, rules, train_scores)
        scored, audits, unknown_rows = scorer.score_many(score_pairs)
    unknown_rows = _dedupe_unknown(unknown_rows)
    write_tsv(reports / "unclassified_effects.tsv", unknown_rows, ["pair", "target", "effect", "value"])
    if unknown_rows and not allow_unclassified:
        _write_update_report(
            reports / "STATIC_UPDATE_REPORT.md",
            baseline,
            snapshot,
            comparison,
            status="REVIEW_REQUIRED",
            confidence=confidence_counts(audits),
            unknown_count=len(unknown_rows),
            notes="New/recomputed pairs contain unclassified effects. Update the rules or known-ignore registry.",
        )
        raise ReviewRequired("Unclassified effects detected")

    pair_scores: dict[str, dict[str, float]] = {}
    for pair in comparison.unchanged_retained:
        pair_scores[pair] = baseline.scores(pair)
    for pair in preserve_modified:
        pair_scores[pair] = baseline.scores(pair)
    pair_scores.update(scored)

    current_pairs = snapshot.upgrade_pairs()
    if set(pair_scores) != current_pairs:
        missing = sorted(current_pairs - set(pair_scores))
        stale = sorted(set(pair_scores) - current_pairs)
        write_pair_list(reports / "post_missing_pairs.tsv", missing)
        write_pair_list(reports / "post_stale_pairs.tsv", stale)
        raise HardAuditFailure(f"Post-generation pair graph mismatch: missing={len(missing)} stale={len(stale)}")

    for scores in pair_scores.values():
        rules.validate_score_map(scores)

    audit_rows = []
    for a in audits:
        row: dict[str, Any] = {
            "pair": a.pair,
            "confidence": a.confidence,
            "nearest_similarity": f"{a.nearest_similarity:.6f}",
            "nearest_analog": a.nearest_analog,
            "rule_categories": ",".join(a.rule_categories),
        }
        row.update({c: f"{a.scores.get(c, 0.0):.6f}" for c in CATEGORIES})
        audit_rows.append(row)
    write_tsv(
        reports / "scoring_audit.tsv",
        audit_rows,
        ["pair", "confidence", "nearest_similarity", "nearest_analog", "rule_categories", *CATEGORIES],
    )

    static_json = {
        "format_version": 1,
        "generator_version": __version__,
        "game": {"version": snapshot.game_version, "steam_build_id": snapshot.steam_build_id},
        "pair_count": len(pair_scores),
        "pairs": {p: pair_scores[p] for p in sorted(pair_scores)},
    }
    write_json(out / "wau_static.json", static_json)
    _write_static_lua(out / "WAU_STATIC.lua", pair_scores, snapshot.game_version, snapshot.steam_build_id)
    write_baseline(out / "next_baseline.json", snapshot, pair_scores, rules.sha256, __version__)

    manifest = {
        "generator_version": __version__,
        "previous_game_version": baseline.game_version,
        "current_game_version": snapshot.game_version,
        "current_steam_build_id": snapshot.steam_build_id,
        "baseline_pairs": len(baseline.pairs),
        "current_ca_upgrade_pairs": len(current_pairs),
        "retained": len(comparison.retained),
        "unchanged_retained": len(comparison.unchanged_retained),
        "modified_retained": len(comparison.modified_retained),
        "modified_preserved": len(preserve_modified),
        "modified_recomputed": len(recompute_modified),
        "removed": len(comparison.removed),
        "added": len(comparison.added),
        "final_pairs": len(pair_scores),
        "unclassified_effects": len(unknown_rows),
        "confidence_counts": confidence_counts(audits),
        "pair_graph_exact": True,
        "status": "PASS" if not unknown_rows else "PASS_WITH_OVERRIDE",
        "rules_sha256": rules.sha256,
    }
    write_json(reports / "generation_manifest.json", manifest)
    _write_update_report(
        reports / "STATIC_UPDATE_REPORT.md",
        baseline,
        snapshot,
        comparison,
        status=manifest["status"],
        confidence=manifest["confidence_counts"],
        unknown_count=len(unknown_rows),
        notes="Stable update completed; retained unchanged scores were preserved exactly.",
    )
    return manifest


def verify_static(db_root: str | Path, static_json_path: str | Path) -> dict[str, Any]:
    snapshot = Snapshot.load(db_root)
    static = json.loads(Path(static_json_path).read_text(encoding="utf-8"))
    pair_scores = static["pairs"]
    current = snapshot.upgrade_pairs()
    found = set(pair_scores)
    missing = sorted(current - found)
    stale = sorted(found - current)
    invalid: list[dict[str, Any]] = []
    for pair, scores in pair_scores.items():
        for cat, value in scores.items():
            if cat not in CATEGORIES or not 0 <= float(value) <= 1:
                invalid.append({"pair": pair, "category": cat, "value": value})
    return {
        "ca_pairs": len(current),
        "static_pairs": len(found),
        "missing": missing,
        "stale": stale,
        "invalid_scores": invalid,
        "status": "PASS" if not missing and not stale and not invalid else "FAIL",
    }


def _write_db_audit_md(path: Path, audit: dict[str, Any]) -> None:
    lines = [
        "# DB Audit Report",
        "",
        f"- Game version: **{audit['game_version']}**",
        f"- Steam build: **{audit['steam_build_id']}**",
        f"- Upgrade pairs: **{audit['upgrade_pair_count']}**",
        f"- Schema issues: **{len(audit['schema_issues'])}**",
        f"- Duplicate key issues: **{len(audit['duplicate_keys'])}**",
        f"- Dangling references: **{len(audit['dangling_references'])}**",
        f"- Result: **{audit['status']}**",
        "",
        "## Tables",
        "",
    ]
    for name, info in audit["table_summary"].items():
        lines.append(f"- `{name}`: {info['rows']} rows")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_update_report(
    path: Path,
    baseline: Baseline,
    snapshot: Snapshot,
    comparison: Any,
    status: str,
    confidence: dict[str, int] | None,
    unknown_count: int,
    notes: str,
) -> None:
    lines = [
        "# Static Update Report",
        "",
        f"- Previous game version: **{baseline.game_version}**",
        f"- Current game version: **{snapshot.game_version}**",
        f"- Baseline pairs: **{len(baseline.pairs)}**",
        f"- Current CA upgrade pairs: **{len(snapshot.upgrade_pairs())}**",
        f"- Retained: **{len(comparison.retained)}**",
        f"- Unchanged retained: **{len(comparison.unchanged_retained)}**",
        f"- Modified retained: **{len(comparison.modified_retained)}**",
        f"- Added: **{len(comparison.added)}**",
        f"- Removed: **{len(comparison.removed)}**",
        f"- Unclassified effects: **{unknown_count}**",
    ]
    if confidence is not None:
        lines.append(
            f"- New/recomputed confidence: **HIGH {confidence['HIGH']} / MEDIUM {confidence['MEDIUM']} / LOW {confidence['LOW']}**"
        )
    lines.extend([f"- Result: **{status}**", "", notes, ""])
    path.write_text("\n".join(lines), encoding="utf-8")
